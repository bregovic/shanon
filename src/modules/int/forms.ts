/**
 * Formulář portálu (smlouva, přihláška): pole, typ, povinnost a kam se hodnota uloží (člen = subjekt adresáře,
 * trvalá / kontaktní adresa, smlouva, nebo jen jako údaj smlouvy). Vyplnění zpracuje `src/server/agreement-portal.ts`,
 * všechny odpovědi zůstanou u smlouvy (`formData`, čitelně `formText`) – do tiskové sestavy jako {form.<klíč>}.
 */
import { Edts, defineEdt, defineEnum, enumEdt, refEdt } from "@/core/edt";
import { defineObject } from "@/core/object";

