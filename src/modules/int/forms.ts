export const form = defineObject({
  id: "int.form",
  table: "int_form",
  label: "@INT:Form",
  labelPlural: "@INT:Forms",
  scope: "company",
  fields: {
    code: { edt: Edts.Code, mandatory: true },
    name: { edt: Edts.Name, mandatory: true },
    /** nadpis kroku s údaji na portálu (prázdné = „Vaše údaje“) */
    heading: { edt: Edts.Description, label: "@INT:FormHeading" },
    intro: { edt: Edts.Notes, label: "@INT:FormIntro" },
  },
  titleField: "name",
  list: ["code", "name"],
  form: [{ label: "@SYS:General", fields: ["code", "name", "heading", "intro"] }],
  unique: [["code"]],
  lines: [{ object: "int.formField", field: "formId", label: "@INT:FormFields" }],
});

const FieldKey = defineEdt({ id: "IntFormKey", kind: "string", label: "@INT:FormKey", maxLength: 40, pattern: /^[a-zA-Z][a-zA-Z0-9_]{0,39}$/, patternMessage: "@INT:FormKeyHelp" });

export const formField = defineObject({
  id: "int.formField",
  table: "int_form_field",
  label: "@INT:FormField",
  labelPlural: "@INT:FormFields",
  scope: "company",
  fields: {
    formId: { edt: refEdt("int.form", "@INT:Form"), mandatory: true },
    sequence: { edt: Edts.Int, label: "@INT:Sequence", default: 10 },
    /** technický název – v tiskové sestavě {form.<klíč>} */
    key: { edt: FieldKey, mandatory: true, help: "@INT:FormKeyHelp" },
    label: { edt: Edts.Description, label: "@INT:FormLabel", mandatory: true },
    kind: { edt: enumEdt(FormFieldKind), mandatory: true, default: "text" },
    required: { edt: Edts.NoYes, label: "@INT:FormRequired" },
    mapping: { edt: enumEdt(FormMapping), mandatory: true, default: "form", help: "@INT:FormMappingHelp" },
    /** výběr: jedna možnost na řádek */
    options: { edt: Edts.Notes, label: "@INT:FormOptions", help: "@INT:FormOptionsHelp" },
    help: { edt: Edts.Description, label: "@INT:FormHelp" },
    width: { edt: enumEdt(FormFieldWidth), mandatory: true, default: "half" },
    /** zobrazit jen když: „klíč=hodnota“ (výběr), „klíč“ (zaškrtnuté) */
    showIf: { edt: Edts.Description, label: "@INT:FormShowIf", help: "@INT:FormShowIfHelp" },
  },
  titleField: "label",
  list: ["sequence", "key", "label", "kind", "required", "mapping", "width"],
  form: [{ label: "@SYS:General", fields: ["formId", "sequence", "key", "label", "kind", "required", "mapping", "options", "help", "width", "showIf"] }],
  unique: [["formId", "key"]],
  defaultSort: { field: "sequence", dir: "asc" },
});

