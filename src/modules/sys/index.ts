import { Edts, defineEdt } from "@/core/edt";
import { defineModule } from "@/core/module";
import { defineObject } from "@/core/object";

export const SeqFormat = defineEdt({
  id: "SeqFormat",
  kind: "string",
  label: "@SYS:SeqFormat",
  maxLength: 40,
  pattern: /\{#+\}/,
  patternMessage: "@SYS:SeqFormatHelp",
});

export const company = defineObject({
  id: "sys.company",
  table: "sys_company",
  label: "@SYS:Company",
  labelPlural: "@SYS:Companies",
  scope: "tenant",
  fields: {
    code: { edt: Edts.Code, mandatory: true },
    name: { edt: Edts.Name, mandatory: true },
    regNo: { edt: Edts.RegNo },
    vatId: { edt: Edts.VatId },
    vatPayer: { edt: Edts.NoYes, label: "@SYS:VatPayer", default: true },
    currency: { edt: Edts.CurrencyCode, mandatory: true, default: "CZK" },
    country: { edt: Edts.CountryCode, mandatory: true, default: "CZ" },
  },
  titleField: "name",
  list: ["code", "name", "regNo", "vatId", "currency"],
  form: [
    { label: "@SYS:General", fields: ["code", "name", "currency", "country"] },
    { label: "@SYS:Identification", fields: ["regNo", "vatId", "vatPayer"] },
  ],
  unique: [["code"]],
  defaultSort: { field: "code", dir: "asc" },
});

export const numberSeq = defineObject({
  id: "sys.numberSeq",
  table: "sys_number_seq",
  label: "@SYS:NumberSeq",
  labelPlural: "@SYS:NumberSeqs",
  scope: "company",
  fields: {
    code: { edt: Edts.Code, mandatory: true },
    name: { edt: Edts.Name, mandatory: true },
    format: { edt: SeqFormat, mandatory: true },
    nextNumber: { edt: Edts.Int, label: "@SYS:NextNumber", mandatory: true, default: 1 },
  },
  titleField: "code",
  list: ["code", "name", "format", "nextNumber"],
  form: [{ label: "@SYS:General", fields: ["code", "name", "format", "nextNumber"] }],
  unique: [["code"]],
  defaultSort: { field: "code", dir: "asc" },
});

