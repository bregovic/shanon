async function sysSetup(data: DataApi) {
  if ((await data.find("sys.currency", {}, { take: 1 })).length) return;
  for (const [code, name, symbol] of [
    ["CZK", "Česká koruna", "Kč"],
    ["EUR", "Euro", "€"],
    ["USD", "Americký dolar", "$"],
  ]) {
    // hotovost v CZK se zaokrouhluje na koruny (zákon o oběhu bankovek a mincí)
    await data.create("sys.currency", { code, name, symbol, cashRoundingUnit: code === "CZK" ? "1" : "0.01" });
  }
}

