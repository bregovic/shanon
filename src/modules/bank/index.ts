export const MatchKind = defineEnum({
  id: "BankMatchKind",
  label: "@BANK:MatchKind",
  values: [
    { value: "none", label: "@BANK:MatchNone" },
    { value: "customer", label: "@BANK:MatchCustomer" },
    { value: "vendor", label: "@BANK:MatchVendor" },
    { value: "customerAdvance", label: "@BANK:MatchCustomerAdvance" },
    { value: "vendorAdvance", label: "@BANK:MatchVendorAdvance" },
    { value: "ledger", label: "@BANK:MatchLedger" },
  ],
});

const BankAccountNum = defineEdt({
  id: "BankAccountNum",
  kind: "string",
  label: "@BANK:AccountNum",
  maxLength: 40,
  pattern: /^(\d{1,6}-)?\d{2,10}\/\d{4}$/,
  patternMessage: "@BANK:AccountNumHelp",
  transform: "trim",
});
const Iban = defineEdt({ id: "Iban", kind: "string", label: "@BANK:Iban", maxLength: 34, pattern: /^[A-Z]{2}\d{2}[A-Z0-9]{10,30}$/, transform: "upper" });
const Text100 = defineEdt({ id: "BankText", kind: "string", label: "@BANK:Message", maxLength: 140 });

export const account = defineObject({
  id: "bank.account",
  table: "bank_account",
  label: "@BANK:Account",
  labelPlural: "@BANK:Accounts",
  scope: "company",
  fields: {
    code: { edt: Edts.Code, mandatory: true },
    name: { edt: Edts.Name, mandatory: true },
    accountNum: { edt: BankAccountNum },
    iban: { edt: Iban },
    currencyId: { edt: refEdt("sys.currency", "@SYS:Currency") },
    glAccountId: { edt: refEdt("gl.account", "@BANK:GlAccount"), mandatory: true },
    blocked: { edt: Edts.NoYes, label: "@GL:Blocked" },
  },
  titleField: "code",
  list: ["code", "name", "accountNum", "iban", "currencyId", "glAccountId", "blocked"],
  form: [
    { label: "@SYS:General", fields: ["code", "name", "accountNum", "iban", "currencyId"] },
    { label: "@GL:Posting", fields: ["glAccountId", "blocked"] },
  ],
  unique: [["code"]],
  defaultSort: { field: "code", dir: "asc" },
  lines: [{ object: "bank.statement", field: "bankAccountId", label: "@BANK:Statements", owned: false }],
  actions: [{ id: "import", label: "@BANK:Import", upload: ".gpc,.txt,.abo" }],
});

export const statement = defineObject({
  id: "bank.statement",
  table: "bank_statement",
  label: "@BANK:Statement",
  labelPlural: "@BANK:Statements",
  scope: "company",
  fields: {
    bankAccountId: { edt: refEdt("bank.account", "@BANK:Account"), mandatory: true },
    statementNum: { edt: Edts.Code, label: "@BANK:StatementNum", mandatory: true },
    date: { edt: Edts.TransDate, mandatory: true, default: "$today" },
    openingBalance: { edt: Edts.Balance, label: "@BANK:Opening" },
    credit: { edt: Edts.Amount, label: "@BANK:Credit", readOnly: true },
    debit: { edt: Edts.Amount, label: "@BANK:Debit", readOnly: true },
    closingBalance: { edt: Edts.Balance, label: "@BANK:Closing", readOnly: true },
    status: { edt: enumEdt(JournalStatus), mandatory: true, default: "draft", readOnly: true },
    voucherId: { edt: refEdt("gl.voucher", "@GL:Voucher"), readOnly: true },
  },
  related: [{ object: "gl.trans", field: "voucherId", label: "@GL:VoucherLines", ref: "voucherId" }, { object: "tax.trans", field: "voucherId", label: "@TAX:VatShort", ref: "voucherId" }],
  titleField: "statementNum",
  list: ["bankAccountId", "statementNum", "date", "openingBalance", "credit", "debit", "closingBalance", "status"],
  form: [
    { label: "@SYS:General", fields: ["bankAccountId", "statementNum", "date", "status", "voucherId"] },
    { label: "@BANK:Balances", fields: ["openingBalance", "credit", "debit", "closingBalance"] },
  ],
  unique: [["bankAccountId", "statementNum"]],
  defaultSort: { field: "date", dir: "desc" },
  lines: [{ object: "bank.statementLine", field: "statementId", label: "@BANK:Lines" }],
  actions: [
    { id: "match", label: "@BANK:AutoMatch", when: { field: "status", equals: "draft" } },
    { id: "post", label: "@GL:Post", when: { field: "status", equals: "draft" } },
  ],
  lockedWhen: { field: "status", equals: "posted" },
});

export const statementLine = defineObject({
  id: "bank.statementLine",
  table: "bank_statement_line",
  label: "@BANK:Line",
  labelPlural: "@BANK:Lines",
  scope: "company",
  fields: {
    statementId: { edt: refEdt("bank.statement", "@BANK:Statement"), mandatory: true },
    lineNum: { edt: Edts.Int, label: "@BANK:LineNum" },
    date: { edt: Edts.TransDate, mandatory: true },
    amount: { edt: Edts.Amount, label: "@BANK:AmountSigned", mandatory: true },
    vs: { edt: Vs },
    counterAccount: { edt: Edts.Description, label: "@BANK:CounterAccount" },
    message: { edt: Text100 },
    matchKind: { edt: enumEdt(MatchKind), readOnly: true, default: "none" },
    customerTransId: { edt: refEdt("ar.trans", "@BANK:CustomerTrans") },
    vendorTransId: { edt: refEdt("ap.trans", "@BANK:VendorTrans") },
    customerAdvanceId: { edt: refEdt("ar.advance", "@AR:Advance") },
    vendorAdvanceId: { edt: refEdt("ap.advance", "@AP:Advance") },
    offsetAccountId: { edt: refEdt("gl.account", "@BANK:OffsetAccount") },
  },
  titleField: "message",
  list: ["lineNum", "date", "amount", "vs", "counterAccount", "message", "matchKind", "customerTransId", "vendorTransId", "customerAdvanceId", "vendorAdvanceId", "offsetAccountId"],
  form: [
    { label: "@SYS:General", fields: ["statementId", "lineNum", "date", "amount", "vs", "counterAccount", "message"] },
    { label: "@BANK:Matching", fields: ["matchKind", "customerTransId", "vendorTransId", "customerAdvanceId", "vendorAdvanceId", "offsetAccountId"] },
  ],
  defaultSort: { field: "lineNum", dir: "asc" },
});

